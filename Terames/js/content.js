window.TERA = window.TERA || {};

/* фиксираният курс, по който сайтът показва левовете под всяка цена */
TERA.EUR_RATE = 1.95583;

/** '17,90' → 17.9 */
TERA.toNum = function (s) {
  if (typeof s === 'number') return s;
  if (!s) return 0;
  var n = parseFloat(String(s).replace(/\s/g, '').replace(',', '.'));
  return isNaN(n) ? 0 : n;
};

/** 17.9 → '17,90' */
TERA.fmt = function (n) {
  return Number(n).toFixed(2).replace('.', ',');
};

/** Евро → лева по фиксирания курс. */
TERA.toLv = function (eur) {
  return TERA.fmt(TERA.toNum(eur) * TERA.EUR_RATE);
};

